#!/bin/sh
# Rebuild foglio-protocollo.css: base.css plus the two default palettes, for a one-line setup.
cd "$(dirname "$0")/.." || exit 1
{
  printf '/* Foglio Protocollo bundle: base.css + palettes/dark-inchiostro.css + palettes/light-carta.css.\n   Generated by scripts/bundle.sh; edit the source files instead. */\n'
  cat base.css palettes/dark-inchiostro.css palettes/light-carta.css
} > foglio-protocollo.css
